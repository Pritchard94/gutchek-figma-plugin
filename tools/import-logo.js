// Converts the master logo SVG (brand/gutchek-logo.svg) into normalised path data for the plugins.
// The navy group holds the seven wordmark letters and the ink half of the mark; the lilac group holds the other half.
// Usage: node tools/import-logo.js   (writes src/brand-paths.ts)
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const svg = fs.readFileSync(path.join(root, 'brand', 'gutchek-logo.svg'), 'utf8');

const groups = [...svg.matchAll(/<g([^>]*)>([\s\S]*?)<\/g>/g)].map((g) => ({
  fill: (g[1].match(/fill="([^"]+)"/) || [])[1],
  paths: [...g[2].matchAll(/<path d="([^"]+)"/g)].map((p) => p[1]),
}));
const ink = groups.find((g) => /241B43/i.test(g.fill));
const lilac = groups.find((g) => /B9A1EF/i.test(g.fill));
if (!ink || !lilac) throw new Error('expected a #241B43 group and a #B9A1EF group');

const numbers = (d) => (d.match(/-?\d+(?:\.\d+)?/g) || []).map(Number);
const bbox = (ds) => {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const d of ds) {
    const n = numbers(d);
    for (let i = 0; i < n.length; i += 2) {
      x0 = Math.min(x0, n[i]); x1 = Math.max(x1, n[i]);
      y0 = Math.min(y0, n[i + 1]); y1 = Math.max(y1, n[i + 1]);
    }
  }
  return { x0, y0, x1, y1, w: x1 - x0, h: y1 - y0 };
};
const transform = (d, fx, fy) => {
  let i = 0;
  return d.replace(/-?\d+(?:\.\d+)?/g, (m) => {
    const v = Number(m);
    const out = i % 2 === 0 ? fx(v) : fy(v);
    i++;
    return String(+out.toFixed(3));
  });
};

// The mark is the ink path whose box sits above the letters, plus the lilac path.
const inkBoxes = ink.paths.map((d) => ({ d, b: bbox([d]) }));
const markInk = inkBoxes.reduce((a, b) => (b.b.y0 < a.b.y0 ? b : a));
const letters = inkBoxes.filter((p) => p !== markInk).sort((a, b) => a.b.x0 - b.b.x0);
const markLilac = lilac.paths[0];

const mark = bbox([markInk.d, markLilac]);
const ms = 48 / Math.max(mark.w, mark.h);
const mox = (48 - mark.w * ms) / 2;
const moy = (48 - mark.h * ms) / 2;
const toMark = (d) => transform(d, (x) => (x - mark.x0) * ms + mox, (y) => (y - mark.y0) * ms + moy);

const word = bbox(letters.map((l) => l.d));
const ws = 48 / word.h;
const toWord = (d) => transform(d, (x) => (x - word.x0) * ws, (y) => (y - word.y0) * ws);

const out = `// Generated by tools/import-logo.js from brand/gutchek-logo.svg. Do not edit by hand.

/** The mark on a 48 by 48 grid: the ink half and the lilac half. */
export const MARK_INK = '${toMark(markInk.d)}';
export const MARK_LILAC = '${toMark(markLilac)}';

/** The GutChek wordmark letters, 48 units tall. */
export const WORD_W = ${+(word.w * ws).toFixed(2)};
export const WORD: string[] = [
${letters.map((l) => "  '" + toWord(l.d) + "',").join('\n')}
];

`;
fs.writeFileSync(path.join(root, 'src', 'brand-paths.ts'), out);
console.log('mark', mark.w.toFixed(1) + 'x' + mark.h.toFixed(1), 'word', word.w.toFixed(1) + 'x' + word.h.toFixed(1), 'letters', letters.length);
